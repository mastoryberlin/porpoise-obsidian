import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';



// Plugin to copy CSS files
const copyCssPlugin = {
    name: 'copy-css',
    setup(build) {
        build.onEnd(async () => {
            const fs = await import('fs/promises');
            const path = await import('path');
            const srcCss = path.join(process.cwd(), 'src', 'features', 'task-graph', 'styles.css');
            const destCss = path.join(process.cwd(), 'styles.css');
            try {
                await fs.copyFile(srcCss, destCss);
                console.log('Copied task-graph styles.css to plugin root');
            } catch (e) {
                console.error('Failed to copy CSS:', e);
            }
        });
    }
};



const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
    plugins: [copyCssPlugin],
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	jsx: 'automatic',
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
